const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const src=fs.readFileSync(path.join(__dirname,"../assets/redzone.js"),"utf8");
const html=fs.readFileSync(path.join(__dirname,"../redzone.html"),"utf8");
assert.doesNotThrow(()=>new Function(src));
assert.match(src,/setInterval\(pollScore,5000\)/);
assert.match(src,/setInterval\(pollNFL,8000\)/);
assert.match(src,/setInterval\(function\(\)\{if\(!document\.hidden&&state\.week\)getProjections\(\);\},150000\)/);
assert.match(src,/function pollScore\(\)/);
assert.match(src,/function pollNFL\(\)/);
assert.match(src,/state\.scoreBusy=true/);
assert.match(src,/state\.espnBusy=true/);
assert.match(src,/state\.scoreRetryAt=Date\.now\(\)\+backoff/);
assert.match(src,/state\.espnRetryAt=Date\.now\(\)/);
assert.match(src,/state\.scoreFailures=0/);
assert.match(src,/state\.espnFailures=0/);
assert.match(src,/document\.addEventListener\("visibilitychange"/);
assert.match(src,/if\(!document\.hidden\)\{tick\(\);getProjections\(\);updateStatus\(\);\}/);
assert.match(src,/function tick\(\)\{[\s\S]*?pollScore\(\);pollNFL\(\);/);
assert.doesNotMatch(src,/setInterval\(function\(\)\{tick\(\);\},18000\)/);
assert.match(html,/5s scores · 8s games/);
assert.match(html,/id="refreshDetail"/);
console.log("Red Zone fast-refresh cadence, independent feed polling, backoff and UI tests passed.");
